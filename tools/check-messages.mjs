import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const sandbox=vm.createContext({});
vm.runInContext(readFileSync(new URL('../messages.js',import.meta.url),'utf8')+';globalThis.status=messageStatus;',sandbox);
const status=sandbox.status;
const known=['mentor','colleague','student'];
const threads={mentor:[{from:'me',text:'Outgoing message',read:false}]};
assert.equal(status.unreadCount(threads),0,'Outgoing messages must never create an unread badge.');
assert.ok(status.receive(threads,{id:'one',contactId:'mentor',text:'Incoming message'},known));
assert.equal(status.unreadCount(threads),1);
assert.equal(status.unreadCount(threads,'mentor'),1);
assert.equal(status.receive(threads,{id:'one',contactId:'mentor',text:'Duplicate event'},known),null);
assert.equal(status.unreadCount(threads),1,'Replayed events must not inflate unread counts.');
assert.ok(status.receive(threads,{id:'two',contactId:'colleague',text:'Another conversation'},known));
assert.equal(status.unreadCount(threads),2);
assert.equal(status.markRead(threads,'mentor'),true);
assert.equal(status.unreadCount(threads),1,'Opening one conversation must preserve other unread counts.');
assert.equal(status.markRead(threads,'mentor'),false);
assert.ok(status.receive(threads,{id:'three',contactId:'mentor',text:'Already visible'},known,true));
assert.equal(status.unreadCount(threads,'mentor'),0,'Incoming messages in the open conversation should be read.');
for(const payload of [{contactId:'unknown',text:'No'},{contactId:'mentor',text:''},{contactId:'mentor',text:'x'.repeat(2001)},{contactId:'mentor',text:'Own message',from:'me'},{contactId:'mentor',text:'Invalid ID',id:4}])assert.equal(status.receive(threads,payload,known),null);
assert.equal(status.unreadCount(JSON.parse(JSON.stringify(threads))),1,'Read status must survive saving and reloading.');
assert.equal(status.markRead(threads,'colleague'),true);
assert.equal(status.unreadCount(threads),0);
console.log('Unread-message checks passed: incoming/outgoing separation, duplicates, per-conversation reads, validation, and persistence.');
